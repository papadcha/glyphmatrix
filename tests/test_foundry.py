import pytest

from glyphmatrix.core.foundry import holder_from_copyright, resolve_foundry
from glyphmatrix.core.parser import parse_font_file

from .fontbuilder import build_test_font


def test_manufacturer_wins_over_other_signals():
    assert resolve_foundry("Monotype Imaging Inc.", "GOOG", "Copyright Google Corporation.") == (
        "Monotype Imaging Inc.",
        "manufacturer",
    )


def test_known_vendor_id_used_when_manufacturer_empty():
    assert resolve_foundry(None, "DYNA", None) == ("DynaComware", "vendor_id")
    assert resolve_foundry("  ", "Glyf", None) == ("Glyph Systems", "vendor_id")


def test_vendor_id_is_case_sensitive():
    # "Mono" (Gemfonts' Arialic Hollow) is not Monotype's "MONO".
    assert resolve_foundry(None, "Mono", "Typeface © Gemfonts") == ("Gemfonts", "copyright")


@pytest.mark.parametrize("placeholder", ["????", "NONE", "UKWN", "PfEd", "", "\x00\x00\x00\x00"])
def test_placeholder_vendor_ids_fall_through_to_copyright(placeholder):
    assert resolve_foundry(None, placeholder, "Copyright Copr.1992 Image Club Graphics, Inc.") == (
        "Image Club Graphics",
        "copyright",
    )


def test_nothing_usable_returns_none():
    assert resolve_foundry(None, "????", "This Font Is Free Of Charge For Urdu Lovers") == (None, None)


@pytest.mark.parametrize(
    ("copyright_text", "holder"),
    [
        ("Copyright 1993 Glyph Systems, Limited Partnership. Typeface Portions (C) The Monotype "
         "Corporation All Rights Reserved.", "Glyph Systems"),
        ("Copyright(c) Founder Corporation.2002", "Founder"),
        ("(C)Copyright DynaComware Corp. 2002", "DynaComware"),
        ("(c) Copyright DynaLab Inc. 1992-1998", "DynaLab"),
        ("Copyright (c) 1981, 1982, 1983, 1989 and 1993, Linotype Library GmbH", "Linotype Library"),
        ("(c) 1999 Nick Curtis. All Rights Reserved.", "Nick Curtis"),
        ("Copyright (c) 2011 by Hussein Alazaat (www.alazaat.com). All rights reserved.", "Hussein Alazaat"),
        ("Digitized data © 2007 Ascender Corporation. All rights reserved.", "Ascender"),
        ("Typeface © Gemfonts", "Gemfonts"),
        ("This Font Is Free Of Charge For Urdu Lovers", None),
        (None, None),
    ],
)
def test_holder_from_copyright(copyright_text, holder):
    assert holder_from_copyright(copyright_text) == holder


def test_parser_falls_back_to_vendor_id(tmp_path):
    font_path = build_test_font(tmp_path / "test.ttf", vendor_id="DYNA")

    assert parse_font_file(font_path).foundry == "DynaComware"


def test_parser_falls_back_to_copyright(tmp_path):
    font_path = build_test_font(
        tmp_path / "test.ttf", copyright="Copyright Copr.1992 Image Club Graphics, Inc."
    )

    assert parse_font_file(font_path).foundry == "Image Club Graphics"


@pytest.mark.parametrize(
    ("copyright_text", "holder"),
    [
        ("(c) 1999 Nick Curtis. All Rights Reserved. Generated by Fontographer", "Nick Curtis"),
        ("Generated by Fontographer 4.1", None),
        ("Typeface © (your company). 2006. All Rights Reserved", None),
    ],
)
def test_holder_ignores_tool_notes_and_templates(copyright_text, holder):
    assert holder_from_copyright(copyright_text) == holder


def test_tool_manufacturer_and_vendor_ids_are_ignored():
    assert resolve_foundry("High-Logic", "HL  ", None) == (None, None)
    assert resolve_foundry(None, "MACR", "Typeface © Melissa Baxter, 2002.") == ("Melissa Baxter", "copyright")


def test_bare_c_after_copyright_is_the_mark():
    assert holder_from_copyright("Copyright c 1992 Southern Software, Inc. All Rights Reserved") == "Southern Software"


def test_holder_in_brackets_or_web_address():
    assert holder_from_copyright("(r) (c) 1999 [T-26] Chicago www.t26.com") == "T-26"
    assert holder_from_copyright("©2004 | www.miniml.com | design by craig kroeger") == "miniml"


def test_manufacturer_that_is_a_copyright_sentence_is_not_a_vendor():
    from glyphmatrix.core.foundry import resolve_foundry
    name, source = resolve_foundry(
        "Digitized data (C) Agfa Monotype Corporation. Neo Sans(TM) is a trademark of Agfa",
        None, "Digitized data (C) 2004 Agfa Monotype Corporation. All rights reserved.")
    assert (name, source) == ("Agfa Monotype", "copyright")


def test_dotted_initials_are_not_a_web_address():
    assert holder_from_copyright("Digital data. Copyright (c) 1992 W.S.I.  All Rights Reserved.") == "W.S.I"


def test_all_rights_reserved_cut_is_case_insensitive():
    assert holder_from_copyright("Copyright c 1992 Southern Software, Inc All Rights Reserved") == "Southern Software"
