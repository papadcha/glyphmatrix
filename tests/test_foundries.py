# ---- a user file ------------------------------------------------------------

def test_user_file_adds_and_replaces_by_name(tmp_path):
    user = _write(tmp_path / "mine.toml", '''
[[foundry]]
name = "Acme Type"
aliases = ["acme"]

[[foundry]]
name = "linotype"
aliases = ["lino mine"]
''')
    catalogue = load_foundries(user)
    assert catalogue.canonical("acme") == "Acme Type"
    assert catalogue.canonical("lino mine") == "linotype"
    assert catalogue.canonical("Linotype-Hell") is None          # the packaged Linotype entry was replaced
    assert load_foundries().canonical("acme") is None            # the packaged one is untouched


def test_set_user_file_changes_the_default_catalogue(tmp_path):
    user = _write(tmp_path / "mine.toml", '[[foundry]]\nname = "Acme Type"\naliases = ["acme"]\n')
    set_user_file(user)
    assert short_vendor("Acme") == "Acme Type"
    set_user_file(None)
    assert short_vendor("Acme") == "Acme"


@pytest.mark.parametrize("body, message", [
    ('[[foundry]]\naliases = ["x"]\n', "no name"),
    ('[[foundry]]\nname = "A"\nkind = "wizard"\n', "kind must be"),
    ('[[foundry]]\nname = "A"\nvendor_ids = ["TOOLONG"]\n', "4 characters"),
    ('[[foundry]]\nname = "A"\npatterns = ["("]\n', "bad pattern"),
    ('[[foundry]]\nname = "A"\nstatus = "maybe"\n', "status must be"),
    ('[[foundry]]\nname = "A"\ncolour = "red"\n', "unknown field"),
])
def test_a_malformed_entry_is_refused_with_its_name(tmp_path, body, message):
    with pytest.raises(ValueError, match=message):
        load_foundries(_write(tmp_path / "bad.toml", body))


# ---- the command line --------------------------------------------------------

def test_cli_list_show_and_unknown_name(tmp_path):
    runner = CliRunner()
    db = ["--db", str(tmp_path / "lib.db")]
    listing = runner.invoke(fontctl, [*db, "foundries", "list", "--kind", "tool"])
    assert listing.exit_code == 0 and "Fontographer" in listing.output and "Brendel" not in listing.output

    shown = runner.invoke(fontctl, [*db, "foundries", "show", "brendel & pabst", "--json"])
    assert json.loads(shown.output)["name"] == "Brendel Informatik"

    missing = runner.invoke(fontctl, [*db, "foundries", "show", "nobody"])
    assert missing.exit_code != 0 and "not in the catalogue" in missing.output


def test_cli_check_reports_signals_and_unknown_only(tmp_path):
    root = _stamped_library(tmp_path / "fonts")
    build_test_font(root / "odd.ttf", family="Odd", copyright="Copyright 1999 Nobody At All")
    runner = CliRunner()
    db = ["--db", str(tmp_path / "lib.db")]

    full = runner.invoke(fontctl, [*db, "foundries", "check", str(root), "--json"])
    rows = {r["file"].rsplit("/", 1)[-1]: r for r in json.loads(full.output)}
    assert rows["bare.ttf"]["organize"] == "Brendel Informatik" and rows["bare.ttf"]["organize_source"] == "stamp"
    assert rows["ss.ttf"]["fold_reissues_into"] == "Brendel Informatik"

    unknown = runner.invoke(fontctl, [*db, "foundries", "check", str(root), "--unknown-only", "--json"])
    assert [r["file"].rsplit("/", 1)[-1] for r in json.loads(unknown.output)] == ["odd.ttf"]


def test_cli_foundries_option_and_fold_reissues_flag(tmp_path):
    root = _stamped_library(tmp_path / "fonts")
    user = _write(tmp_path / "mine.toml", '[[foundry]]\nname = "Acme Type"\naliases = ["southern software"]\n')
    runner = CliRunner()
    db = ["--db", str(tmp_path / "lib.db")]

    default = runner.invoke(fontctl, [*db, "organize", str(root), "--json"])
    assert {i["source"].rsplit("/", 1)[-1]: i["vendor"] for i in json.loads(default.output)["items"]}["ss.ttf"] \
        == "Southern Software"
    folded = runner.invoke(fontctl, [*db, "organize", str(root), "--fold-reissues", "--json"])
    assert {i["source"].rsplit("/", 1)[-1]: i["vendor"] for i in json.loads(folded.output)["items"]}["ss.ttf"] \
        == "Brendel Informatik"
    own = runner.invoke(fontctl, [*db, "--foundries", str(user), "organize", str(root), "--json"])
    assert {i["source"].rsplit("/", 1)[-1]: i["vendor"] for i in json.loads(own.output)["items"]}["ss.ttf"] \
        == "Acme Type"


def test_cli_refuses_a_malformed_foundries_file(tmp_path):
    bad = _write(tmp_path / "bad.toml", '[[foundry]]\nkind = "foundry"\n')
    result = CliRunner().invoke(fontctl, ["--db", str(tmp_path / "lib.db"), "--foundries", str(bad), "foundries", "list"])
