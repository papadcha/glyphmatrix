"""Resolve a font's foundry when nameID 8 (Manufacturer) is empty.

Many real-world fonts leave nameID 8 blank. Resolution order, most to least
reliable:

1. nameID 8 (Manufacturer) — what the font says about itself.
2. OS/2.achVendID mapped to a name — the vendor ID registered with Microsoft.
   Only well-known IDs are mapped; unknown IDs are not guessed from.
3. The holder named in the copyright string (nameID 0) — last resort, since
   copyright can name a commissioner or a later owner rather than the maker.

Returns the foundry name and which signal it came from, so callers can show
how trustworthy the value is.
"""
from __future__ import annotations

import re

# Vendor IDs are case-sensitive 4-byte tags ("MONO" != "Mono").
VENDOR_IDS: dict[str, str] = {
    "1ASC": "Ascender",
    "ADBE": "Adobe",
    "APPL": "Apple",
    "B&H ": "Bigelow & Holmes",
    "BITS": "Bitstream",
    "DAMA": "Dalton Maag",
    "DYNA": "DynaComware",
    "FTH ": "Font House",
    "GOOG": "Google",
    "Glyf": "Glyph Systems",
    "H&FJ": "Hoefler & Co.",
    "ITC ": "ITC",
    "LINO": "Linotype",
    "MONO": "Monotype",
    "MS  ": "Microsoft",
    "MSFT": "Microsoft",
    "TPTC": "Test Pilot Collective",
    "URW ": "URW",
    "ULA ": "Underware",
}

# Tool defaults and placeholders that say nothing about who made the font.
_PLACEHOLDER_VENDOR_IDS = {"", "????", "NONE", "UKWN", "PfEd", "XXXX", "\x00\x00\x00\x00"}
# Vendor IDs that font editors write by default — they name the tool, not the
# foundry: FontCreator (High-Logic), Fontographer (Macromedia/Altsys), FontLab (Pyrus).
_TOOL_VENDOR_IDS = {"HL  ", "MACR", "Alts", "ALTS", "pyrs", "PYRS"}
# Strings font editors leave in Manufacturer/Designer/Copyright when the
# author never filled them in.
_TOOL_DEFAULT_TEXT = re.compile(
    r"high-logic|erwin denissen|fontographer|macromedia|altsys|fontlab|pyrus|fontforge|"
    r"\(your company\)|your name|generated by|created (?:with|by) .*(?:creator|editor)",
    re.IGNORECASE,
)


_TOOL_NOTE = re.compile(r"\b(?:generated|converted|created)\s+(?:by|with|from)\b", re.IGNORECASE)


def is_tool_default(text: str | None) -> bool:
    """True when a name-table string is a font editor's placeholder, not real data."""
    return bool(text and _TOOL_DEFAULT_TEXT.search(text))


def clean_designer(designer: str | None) -> str | None:
    """nameID 9 without tool placeholders or a leading "designed by"."""
    if not designer or is_tool_default(designer):
        return None
    designer = re.sub(r"^\s*designed\s+by\s+", "", designer.strip(), flags=re.IGNORECASE)
    return designer.strip(" .") or None

_COMPANY_SUFFIX = re.compile(
    r"[,\s]+(Inc|Incorporated|Ltd|Limited|Corp|Corporation|Co|Company|GmbH|AG|LLC|plc|S\.A|"
    r"Limited Partnership)\.?$",
    re.IGNORECASE,
)
# "Copyright c 1992 X" — a bare "c" after the word is the © sign typed as a letter.
_COPYRIGHT_MARK = re.compile(r"(?:copyright(?:\s+c\b)?|copr\.?|\(c\)|©)", re.IGNORECASE)
# nameID 8 holding a copyright/trademark sentence instead of a name.
_SENTENCE_LIKE = re.compile(r"\(c\)|©|\(tm\)|™|trademark|all rights|\bcopyright\b|registered in", re.IGNORECASE)
_DOMAIN = re.compile(r"^(?:https?://|www\.)(?:www\.)?([a-z0-9][a-z0-9-]*)\.[a-z]{2,}\b", re.IGNORECASE)
_YEARS = re.compile(r"\b(?:19|20)\d{2}\b(?:\s*(?:[-–,/]|,?\s*and)\s*(?:(?:19|20)\d{2}|\d{2})\b)*")


def holder_from_copyright(copyright_text: str | None, keep_suffix: bool = False) -> str | None:
    """Pull the copyright holder's name out of a nameID 0 string, or None.
    keep_suffix: leave "Inc", "Ltd", "GmbH"... on the name."""
    if not copyright_text:
        return None
    # Drop a trailing tool note ("... Generated by Fontographer 4.1") but keep
    # the real claim before it; a string that is only a template gives None.
    text = _TOOL_NOTE.split(copyright_text, maxsplit=1)[0].strip()
    if not text or is_tool_default(text):
        return None
    match = _COPYRIGHT_MARK.search(text)
    if not match:
        return None
    rest = text[match.end():]
    # Strip any further copyright marks, years and "by" before the name.
    while True:
        stripped = _COPYRIGHT_MARK.sub("", rest, count=1) if _COPYRIGHT_MARK.match(rest.lstrip()) else rest
        stripped = stripped.lstrip(" .:,")
        stripped = _YEARS.sub("", stripped, count=1) if _YEARS.match(stripped) else stripped
        stripped = re.sub(r"^\s*(?:by)\s+", "", stripped, flags=re.IGNORECASE).lstrip(" .:,")
        if stripped == rest:
            break
        rest = stripped
    # "(r) (c) 1999 [T-26] Chicago ..." — a bracketed name straight after the year.
    bracketed = re.match(r"\[([^\]]+)\]", rest)
    if bracketed:
        rest = bracketed.group(1)
    else:
        # "©2004 | www.miniml.com | design by ..." — separators, then a web address.
        rest = rest.lstrip(" |/-–—:,")
        domain = _DOMAIN.match(rest)
        if domain:
            rest = domain.group(1)
    # The name runs until a sentence break, bracket, year or "All rights".
    name = re.split(r"\s*(?:[;(\[]|\.\s|\.$|\.(?=\d)|,\s*All rights|\s+All rights|\s+(?:19|20)\d{2}\b)",
                    rest, maxsplit=1, flags=re.IGNORECASE)[0]
    name = name.strip(" .,")
    if not keep_suffix:
        name = _COMPANY_SUFFIX.sub("", name).strip(" .,")
    if not name or not name[0].isalpha() or len(name) > 60:
        return None
    return name


def resolve_foundry(
    manufacturer: str | None,
    vendor_id: str | None,
    copyright_text: str | None,
) -> tuple[str | None, str | None]:
    """Return (foundry, source), source being 'manufacturer', 'vendor_id',
    'copyright' or None when nothing usable was found."""
    if (manufacturer and manufacturer.strip() and not is_tool_default(manufacturer)
            and not _SENTENCE_LIKE.search(manufacturer) and len(manufacturer.strip()) <= 60):
        return manufacturer.strip(), "manufacturer"
    if vendor_id is not None and vendor_id not in _PLACEHOLDER_VENDOR_IDS | _TOOL_VENDOR_IDS:
        name = VENDOR_IDS.get(vendor_id)
        if name:
            return name, "vendor_id"
    holder = holder_from_copyright(copyright_text)
    if holder:
        return holder, "copyright"
    return None, None


def copyright_years(copyright_text: str | None) -> list[int]:
    """Every distinct four-digit year (1970-2099) in a copyright string, sorted.
    Ranges like "1990-1992" give both ends, not the years in between."""
    if not copyright_text:
        return []
    years = {int(y) for y in re.findall(r"(?<!\d)((?:19[7-9]|20\d)\d)(?!\d)", copyright_text)}
    return sorted(years)
