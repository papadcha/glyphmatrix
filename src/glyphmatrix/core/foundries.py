"""The catalogue of foundries, publishers, tools and licences (foundries.toml).

One place that knows who a name, a vendor ID or a unique-ID stamp stands for,
replacing the vendor-ID table in foundry.py, the alias table in organize.py and
part of tidy_rules.toml. Everything is data: a [[foundry]] entry per publisher.

    catalogue = load_foundries()                 # the packaged entries
    catalogue = load_foundries("mine.toml")      # + a user file; same `name` replaces
    catalogue.canonical("Linotype-Hell")         # -> "Linotype"
    catalogue.by_vendor_id("ADBE")               # -> Foundry(name="Adobe", ...)
    catalogue.by_stamp("Brendel            :Aldine")
    catalogue.is_non_publisher("Generated by Fontographer 3.5")   # -> True

The CLI loads ~/.glyphmatrix/foundries.toml (or --foundries FILE) once at start
through set_user_file(); the core never reads the user's home by itself, so
tests and library callers see only the packaged catalogue unless they ask.
"""
from __future__ import annotations

import re
import tomllib
import unicodedata
from dataclasses import dataclass, field
from functools import lru_cache
from importlib import resources
from pathlib import Path

KINDS = ("foundry", "person", "project", "tool", "licence")
STATUSES = ("confirmed", "inferred", "user-decision")
NON_PUBLISHER_KINDS = ("tool", "licence")
_FIELDS = {
    "name", "holder", "kind", "aliases", "prefixes", "vendor_ids", "stamps", "patterns",
    "reissues", "parent", "related", "status", "decided", "sources", "notes",
}


def _key(text: str) -> str:
    """Case, accent and spacing-insensitive form used to compare names."""
    text = unicodedata.normalize("NFKD", text.replace("‐", "-")).casefold()
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return re.sub(r"\s+", " ", text).strip(" -,.;:")


@dataclass(frozen=True)
class Foundry:
    name: str
    holder: str = ""
    kind: str = "foundry"
    aliases: tuple[str, ...] = ()
    prefixes: tuple[str, ...] = ()
    vendor_ids: tuple[str, ...] = ()
    stamps: tuple[str, ...] = ()
    patterns: tuple[str, ...] = ()
    reissues: tuple[str, ...] = ()
    parent: str = ""
    related: str = ""
    status: str = ""
    decided: str = ""
    sources: tuple[str, ...] = ()
    notes: str = ""

    @property
    def tidy_name(self) -> str:
        """The folder name under `--profile tidy`."""
        return self.holder or self.name

    @property
    def publisher(self) -> bool:
        return self.kind not in NON_PUBLISHER_KINDS


def _entry(raw: dict, origin: str) -> Foundry:
    unknown = set(raw) - _FIELDS
    if unknown:
        raise ValueError(f"{origin}: unknown field(s) {', '.join(sorted(unknown))} in foundry {raw.get('name')!r}")
    name = str(raw.get("name", "")).strip()
    if not name:
        raise ValueError(f"{origin}: a [[foundry]] entry has no name")
    kind = raw.get("kind", "foundry")
    if kind not in KINDS:
        raise ValueError(f"{origin}: foundry {name!r}: kind must be one of {', '.join(KINDS)}, not {kind!r}")
    status = raw.get("status", "")
    if status and status not in STATUSES:
        raise ValueError(f"{origin}: foundry {name!r}: status must be one of {', '.join(STATUSES)}, not {status!r}")
    for tag in raw.get("vendor_ids", []):
        if len(tag) != 4:
            raise ValueError(f"{origin}: foundry {name!r}: vendor ID {tag!r} must be 4 characters")
    patterns = tuple(raw.get("patterns", []))
    for pattern in patterns:
        try:
            re.compile(pattern)
        except re.error as exc:
            raise ValueError(f"{origin}: foundry {name!r}: bad pattern {pattern!r}: {exc}") from exc

    def many(field_name: str) -> tuple[str, ...]:
        return tuple(str(v) for v in raw.get(field_name, []))

    return Foundry(
        name=name, holder=str(raw.get("holder", "")).strip(), kind=kind,
        aliases=many("aliases"), prefixes=many("prefixes"), vendor_ids=many("vendor_ids"),
        stamps=many("stamps"), patterns=patterns, reissues=many("reissues"),
        parent=str(raw.get("parent", "")), related=str(raw.get("related", "")), status=status,
        decided=str(raw.get("decided", "")), sources=many("sources"), notes=str(raw.get("notes", "")).strip(),
    )


class Foundries:
    def __init__(self, entries: list[Foundry]):
        self.entries = entries
        self._by_name: dict[str, Foundry] = {}
        self._by_alias: dict[str, Foundry] = {}
        self._by_vendor_id: dict[str, Foundry] = {}
        self._prefixes: list[tuple[str, Foundry]] = []
        self._stamps: list[tuple[str, Foundry]] = []
        self._patterns: list[tuple[re.Pattern[str], Foundry]] = []
        for entry in entries:
            self._by_name[_key(entry.name)] = entry
            self._by_alias.setdefault(_key(entry.name), entry)
            for alias in entry.aliases:
                self._by_alias[_key(alias)] = entry
            for tag in entry.vendor_ids:
                self._by_vendor_id[tag] = entry
            self._prefixes += [(_key(p), entry) for p in entry.prefixes]
            self._stamps += [(s, entry) for s in entry.stamps]
            self._patterns += [(re.compile(p, re.IGNORECASE), entry) for p in entry.patterns]
        self._prefixes.sort(key=lambda kv: -len(kv[0]))

    # ---- lookups -----------------------------------------------------------
    def get(self, name: str | None) -> Foundry | None:
        """The entry called `name` or having it as an alias."""
        if not name:
            return None
        key = _key(name)
        found = self._by_alias.get(key)
        if found is None:
            found = next((entry for prefix, entry in self._prefixes if key.startswith(prefix)), None)
        return found

    def canonical(self, name: str | None) -> str | None:
        """The folder name for `name` when the catalogue knows it (publishers only)."""
        found = self.get(name)
        return found.name if found is not None and found.publisher else None

    def by_vendor_id(self, tag: str | None) -> Foundry | None:
        return self._by_vendor_id.get(tag) if tag is not None else None

    def vendor_ids(self, *, tools: bool) -> dict[str, str]:
        """{tag: name} for publishers (tools=False) or for editor tools (tools=True)."""
        return {t: f.name for t, f in self._by_vendor_id.items() if f.publisher != tools}

    def by_stamp(self, *texts: str | None) -> Foundry | None:
        """The publisher whose stamp one of the texts starts with (nameID 3 / 5)."""
        for text in texts:
            if not text:
                continue
            for stamp, entry in self._stamps:
                if text.startswith(stamp) and entry.publisher:
                    return entry
        return None

    def is_non_publisher(self, text: str | None, kinds: tuple[str, ...] = NON_PUBLISHER_KINDS) -> bool:
        """True when the text is a placeholder of one of `kinds` (a tool, a licence), not a publisher."""
        if not text:
            return False
        for pattern, entry in self._patterns:
            if entry.kind in kinds and pattern.search(text):
                return True
        found = self.get(text)
        return found is not None and found.kind in kinds

    def folded_into(self, holder: str | None, *stamp_texts: str | None) -> Foundry | None:
        """The foundry whose stamp is on the font and whose `reissues` name `holder`:
        under --fold-reissues the font belongs to that foundry, not to its original holder."""
        packager = self.by_stamp(*stamp_texts)
        if packager is None or not holder or not packager.reissues:
            return None
        wanted = _key(holder)
        for name in packager.reissues:
            known = self.get(name)
            if _key(name) == wanted or (known is not None and known is self.get(holder)):
                return packager
        return None

    # ---- tidy profile ------------------------------------------------------
    def tidy_exact(self) -> dict[str, str]:
        """{name as the font may spell it: holder folder} for publishers."""
        out: dict[str, str] = {}
        for entry in self.entries:
            if not entry.publisher:
                continue
            for alias in (entry.name, *entry.aliases):
                out[_key(alias)] = entry.tidy_name
        return out

    def tidy_prefix(self) -> dict[str, str]:
        return {_key(p): entry.tidy_name for entry in self.entries if entry.publisher for p in entry.prefixes}

    def non_publisher_patterns(self) -> list[str]:
        return [p for entry in self.entries if not entry.publisher for p in entry.patterns]


def _parse(text: str, origin: str) -> list[Foundry]:
    data = tomllib.loads(text)
    return [_entry(raw, origin) for raw in data.get("foundry", [])]


def load_foundries(extra: str | Path | None = None) -> Foundries:
    """The packaged catalogue, with a user file merged on top: an entry with the
    same name (ignoring case) replaces the packaged one, others are added."""
    entries = _parse(resources.files("glyphmatrix.core").joinpath("foundries.toml").read_text("utf-8"),
                     "foundries.toml")
    if extra is not None:
        path = Path(extra)
        by_name = {_key(e.name): i for i, e in enumerate(entries)}
        for entry in _parse(path.read_text("utf-8"), str(path)):
            slot = by_name.get(_key(entry.name))
            if slot is None:
                by_name[_key(entry.name)] = len(entries)
                entries.append(entry)
            else:
                entries[slot] = entry
    return Foundries(entries)


_user_file: Path | None = None


def set_user_file(path: str | Path | None) -> None:
    """Merge this file over the packaged catalogue for default_foundries() from now on."""
    global _user_file
    _user_file = Path(path) if path else None
    default_foundries.cache_clear()


def user_file() -> Path | None:
    return _user_file


@lru_cache(maxsize=1)
def default_foundries() -> Foundries:
    return load_foundries(_user_file)
